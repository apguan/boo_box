    private static func translateAptCommandIfNeeded(_ cmd: String) -> (command: String, warning: String)? {
        guard cmd.contains("apt-get") || cmd.range(of: #"\bapt\s+install\b"#, options: .regularExpression) != nil else {
            return nil
        }
        // Extract package tokens following `apt-get install` or `apt install`
        guard let range = cmd.range(of: #"apt(-get)?\s+install\b[^&;|]*"#, options: .regularExpression) else {
            return nil
        }
        let segment = String(cmd[range])
        let words = segment.split(whereSeparator: { $0.isWhitespace }).map(String.init)
        var rawPkgs: [String] = []
        var sawInstall = false
        for w in words {
            if !sawInstall {
                if w == "install" { sawInstall = true }
                continue
            }
            if w.hasPrefix("-") { continue }
            rawPkgs.append(w)
        }
        guard !rawPkgs.isEmpty else { return nil }

        var apkPkgs: [String] = []
        var unmapped: [String] = []
        for p in rawPkgs {
            let basePkg = p.split(separator: "=").first.map(String.init) ?? p
            if let mapped = aptToApkMap[basePkg.lowercased()] {
                if !apkPkgs.contains(mapped) { apkPkgs.append(mapped) }
            } else {
                unmapped.append(basePkg)
            }
        }

        guard !apkPkgs.isEmpty else {
            return (
                "echo '[boo_box/dockerfile] skipped Debian-only apt-get install (\(rawPkgs.joined(separator: ", ")))'",
                "Skipped Debian-only apt-get packages (\(rawPkgs.joined(separator: ", "))) — not mapped to Alpine apk."
            )
        }

        let apkCmd = "apk add --no-cache \(apkPkgs.joined(separator: " "))"
        let warn: String
        if unmapped.isEmpty {
            warn = "Translated `apt-get install` → `\(apkCmd)` for Alpine Linux microVM."
        } else {
            warn = "Translated `apt-get install` → `\(apkCmd)` (unmapped Debian packages skipped: \(unmapped.joined(separator: ", ")))."
        }
        return (apkCmd, warn)
    }

    // MARK: - Token & Substitution Helpers

    private static func stripLeadingBuildkitFlags(_ raw: String) -> String {
        var s = raw.trimmingCharacters(in: .whitespaces)
        while s.hasPrefix("--") {
            guard let sp = s.firstIndex(where: { $0.isWhitespace }) else { return "" }
            s = String(s[sp...]).trimmingCharacters(in: .whitespaces)
        }
        return s
    }

    private static func parseEnvPairs(_ raw: String) -> [(String, String)] {
        let trimmed = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return [] }
        let tokens = splitRespectingQuotes(trimmed)
        // Modern syntax: every token has `=` (or first token contains `=`)
        if let first = tokens.first, first.contains("=") {
            var pairs: [(String, String)] = []
            for tok in tokens {
                guard let eq = tok.firstIndex(of: "=") else { continue }
                let k = String(tok[..<eq])
                let v = unquote(String(tok[tok.index(after: eq)...]))
                pairs.append((k, v))
            }
            return pairs
        }
        // Legacy syntax: `ENV KEY value with spaces`
        if let sp = trimmed.firstIndex(where: { $0.isWhitespace }) {
            let k = String(trimmed[..<sp])
            let v = unquote(String(trimmed[sp...]).trimmingCharacters(in: .whitespaces))
            return [(k, v)]
        }
        return []
    }

    private static func splitRespectingQuotes(_ s: String) -> [String] {
        var result: [String] = []
        var current = ""
        var quote: Character? = nil
        var escaped = false

        for ch in s {
            if escaped {
                current.append(ch)
                escaped = false
                continue
            }
            if ch == "\\" && quote != "'" {
                escaped = true
                current.append(ch)
                continue
            }
            if let q = quote {
                current.append(ch)
                if ch == q { quote = nil }
                continue
            }
            if ch == "\"" || ch == "'" {
                quote = ch
                current.append(ch)
                continue
            }
            if ch.isWhitespace {
                if !current.isEmpty {
                    result.append(current)
                    current = ""
                }
            } else {
                current.append(ch)
            }
        }
        if !current.isEmpty {
            result.append(current)
        }
        return result
    }

    private static func parseJSONStringArray(_ raw: String) -> [String]? {
        let t = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        guard t.hasPrefix("["), t.hasSuffix("]"), let data = t.data(using: .utf8) else { return nil }
        return try? JSONDecoder().decode([String].self, from: data)
    }

    private static func unquote(_ s: String) -> String {
        let t = s.trimmingCharacters(in: .whitespacesAndNewlines)
        if t.count >= 2, ((t.first == "\"" && t.last == "\"") || (t.first == "'" && t.last == "'")) {
            return String(t.dropFirst().dropLast())
        }
        return t
    }

    private static func expandArgs(_ input: String, args: [String: String]) -> String {
        guard !args.isEmpty, input.contains("$") else { return input }
        var out = input
        // Handle ${VAR:-default} and ${VAR} first
        if let regex = try? NSRegularExpression(pattern: #"\$\{([A-Za-z_][A-Za-z0-9_]*)(:-([^}]*))?\}"#) {
            let ns = out as NSString
            let matches = regex.matches(in: out, range: NSRange(location: 0, length: ns.length))
            for m in matches.reversed() {
                let name = ns.substring(with: m.range(at: 1))
                let defVal = m.range(at: 3).location != NSNotFound ? ns.substring(with: m.range(at: 3)) : nil
                if let val = args[name], !val.isEmpty {
                    out = (out as NSString).replacingCharacters(in: m.range, with: val)
                } else if let defVal {
                    out = (out as NSString).replacingCharacters(in: m.range, with: defVal)
                }
            }
        }
        // Handle bare $VAR only for declared ARG keys (preserve shell runtime vars like $PATH!)
        for (k, v) in args.sorted(by: { $0.key.count > $1.key.count }) {
            if let regex = try? NSRegularExpression(pattern: "\\$\(NSRegularExpression.escapedPattern(for: k))(?![A-Za-z0-9_])") {
                out = regex.stringByReplacingMatches(
                    in: out,
                    range: NSRange(location: 0, length: (out as NSString).length),
                    withTemplate: NSRegularExpression.escapedTemplate(for: v)
                )
            }
        }
        return out
    }

    private static func isValidEnvKey(_ key: String) -> Bool {
        key.range(of: #"^[A-Za-z_][A-Za-z0-9_]*$"#, options: .regularExpression) != nil
    }

    private static func shQuoteSimple(_ s: String) -> String {
        "'" + s.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }

    private static func shQuoteIfNeeded(_ s: String) -> String {
        let safe = CharacterSet.alphanumerics.union(CharacterSet(charactersIn: "/._-:=+@"))
        if !s.isEmpty && s.unicodeScalars.allSatisfy({ safe.contains($0) }) {
            return s
        }
        return shQuoteSimple(s)
    }

    private static func deduplicatePreservingOrder(_ list: [String]) -> [String] {
        var seen = Set<String>()
        var out: [String] = []
        for item in list where seen.insert(item).inserted {
            out.append(item)
        }
        return out
    }
