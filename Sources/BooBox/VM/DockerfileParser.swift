import Foundation

/// Parsed representation of a Dockerfile / Containerfile for Private Linux MicroVM setup.
struct ParsedDockerfile: Equatable, Sendable {
    enum Step: Equatable, Sendable {
        case env(key: String, value: String)
        case workdir(String)
        case copy(sources: [String], destination: String, chmod: String?)
        case addURL(url: String, destination: String)
        case run(command: String, originalCommand: String?, translatedFromApt: Bool)
        case note(String)
    }

    let sourceURL: URL
    let contextDirectoryURL: URL
    let baseImage: String
    let stageName: String?
    let stageCount: Int
    let baseRuntimePackages: [String]
    let installsBun: Bool
    let envVars: [(key: String, value: String)]
    let finalWorkdir: String?
    let exposedPorts: [String]
    let defaultCommand: String?
    let steps: [Step]
    let warnings: [String]
    let requiresCopyContext: Bool

    static func == (lhs: ParsedDockerfile, rhs: ParsedDockerfile) -> Bool {
        lhs.sourceURL == rhs.sourceURL
            && lhs.contextDirectoryURL == rhs.contextDirectoryURL
            && lhs.baseImage == rhs.baseImage
            && lhs.stageName == rhs.stageName
            && lhs.stageCount == rhs.stageCount
            && lhs.baseRuntimePackages == rhs.baseRuntimePackages
            && lhs.installsBun == rhs.installsBun
            && lhs.envVars.count == rhs.envVars.count
            && zip(lhs.envVars, rhs.envVars).allSatisfy { $0.key == $1.key && $0.value == $1.value }
            && lhs.finalWorkdir == rhs.finalWorkdir
            && lhs.exposedPorts == rhs.exposedPorts
            && lhs.defaultCommand == rhs.defaultCommand
            && lhs.steps == rhs.steps
            && lhs.warnings == rhs.warnings
            && lhs.requiresCopyContext == rhs.requiresCopyContext
    }

    var envCount: Int { envVars.count }
    var runCount: Int {
        steps.reduce(0) { acc, step in
            if case .run = step { return acc + 1 }
            return acc
        }
    }
    var copyCount: Int {
        steps.reduce(0) { acc, step in
            switch step {
            case .copy, .addURL: return acc + 1
            default: return acc
            }
        }
    }

    var summaryLine: String {
        var parts: [String] = []
        if !baseImage.isEmpty {
            parts.append("FROM \(baseImage)")
        }
        if let wd = finalWorkdir {
            parts.append("WORKDIR \(wd)")
        }
        if envCount > 0 { parts.append("\(envCount) ENV") }
        if copyCount > 0 { parts.append("\(copyCount) COPY") }
        if runCount > 0 { parts.append("\(runCount) RUN") }
        if !exposedPorts.isEmpty {
            parts.append("EXPOSE \(exposedPorts.joined(separator: ", "))")
        }
        return parts.isEmpty ? "Empty Dockerfile" : parts.joined(separator: " · ")
    }

    /// Generates the POSIX `/bin/sh` provisioning snippet executed inside the Alpine arm64 microVM.
    func generateProvisioningScript(
        contextMountPoint: String?,
        isOffline: Bool
    ) -> String {
        var lines: [String] = [
            "echo '[boo_box/dockerfile] applying \(Self.shDoubleEscape(sourceURL.lastPathComponent)) (FROM \(Self.shDoubleEscape(baseImage.isEmpty ? "alpine" : baseImage)))'",
        ]

        // 1. Auto-install inferred runtime toolchain from FROM image (e.g. node, python, go, rust, ruby, bun)
        if !isOffline && (!baseRuntimePackages.isEmpty || installsBun) {
            if !baseRuntimePackages.isEmpty {
                let pkgs = baseRuntimePackages.joined(separator: " ")
                lines.append("echo '[boo_box/dockerfile] installing base runtime packages: \(pkgs)'")
                lines.append("apk add --no-cache \(pkgs) || echo '[boo_box/dockerfile] warning: some base runtime packages failed'")
            }
            if installsBun {
                lines.append("if ! command -v bun >/dev/null 2>&1; then curl -fsSL https://bun.sh/install | bash && export PATH=\"/root/.bun/bin:$PATH\"; fi")
            }
        }

        // 2. Persist Dockerfile ENV vars cleanly into /root/.boobox-dockerfile-env.sh (sourced by zsh + profile.d)
        var envScriptLines: [String] = ["# Auto-generated by boo_box from \(sourceURL.lastPathComponent)"]
        if installsBun {
            envScriptLines.append("export PATH=\"/root/.bun/bin:$PATH\"")
        }
        for pair in envVars {
            let escaped = Self.shDoubleEscapePreservingVars(pair.value)
            envScriptLines.append("export \(pair.key)=\"\(escaped)\"")
        }
        if envScriptLines.count > 1 {
            let body = envScriptLines.joined(separator: "\n") + "\n"
            let b64 = Data(body.utf8).base64EncodedString()
            lines.append("echo '\(b64)' | base64 -d > /root/.boobox-dockerfile-env.sh && chmod 644 /root/.boobox-dockerfile-env.sh")
            lines.append("mkdir -p /etc/profile.d && cp /root/.boobox-dockerfile-env.sh /etc/profile.d/boobox-dockerfile.sh")
            lines.append("grep -q '.boobox-dockerfile-env.sh' /root/.zshrc 2>/dev/null || printf '\\n[ -f /root/.boobox-dockerfile-env.sh ] && source /root/.boobox-dockerfile-env.sh\\n' >> /root/.zshrc")
            lines.append(". /root/.boobox-dockerfile-env.sh")
        }

        // 3. Replay Dockerfile WORKDIR / ENV / COPY / RUN instructions in exact order
        var currentWorkdir = "/root"
        lines.append("cd /root")
        for step in steps {
            switch step {
            case .env(let key, let value):
                let escaped = Self.shDoubleEscapePreservingVars(value)
                lines.append("export \(key)=\"\(escaped)\"")

            case .workdir(let dir):
                currentWorkdir = dir
                lines.append("mkdir -p \(Self.shSingleQuote(dir)) && cd \(Self.shSingleQuote(dir))")

            case .copy(let sources, let destination, let chmodMode):
                guard let ctx = contextMountPoint else {
                    lines.append("echo '[boo_box/dockerfile] skipping COPY \(Self.shSingleQuote(sources.joined(separator: " "))) -> \(Self.shSingleQuote(destination)) (context copy disabled)'")
                    continue
                }
                let resolvedDst = Self.resolveGuestDest(destination, workdir: currentWorkdir)
                let dstIsDir = destination.hasSuffix("/") || destination == "." || destination == "./" || sources.count > 1
                if dstIsDir {
                    lines.append("mkdir -p \(Self.shSingleQuote(resolvedDst))")
                } else {
                    let parent = (resolvedDst as NSString).deletingLastPathComponent
                    if !parent.isEmpty && parent != "/" {
                        lines.append("mkdir -p \(Self.shSingleQuote(parent))")
                    }
                }
                for src in sources {
                    let trimmedSrc = Self.normalizeRelativeSource(src)
                    guard Self.isSafeRelativeSource(trimmedSrc) else {
                        lines.append("echo '[boo_box/dockerfile] blocked unsafe COPY path: \(Self.shSingleQuote(src))'")
                        continue
                    }
                    let fullSrc: String
                    if trimmedSrc == "." || trimmedSrc.isEmpty {
                        fullSrc = "\(ctx)/."
                    } else {
                        fullSrc = "\(ctx)/\(trimmedSrc)"
                    }
                    // Allow glob characters (*, ?, [) to expand inside the mounted context dir while quoting the rest
                    if fullSrc.contains("*") || fullSrc.contains("?") || fullSrc.contains("[") {
                        lines.append("cp -a \(fullSrc) \(Self.shSingleQuote(resolvedDst)) 2>/dev/null || echo '[boo_box/dockerfile] warning: COPY glob matched nothing: \(Self.shSingleQuote(src))'")
                    } else {
                        lines.append("cp -a \(Self.shSingleQuote(fullSrc)) \(Self.shSingleQuote(resolvedDst)) || echo '[boo_box/dockerfile] warning: COPY failed for \(Self.shSingleQuote(src))'")
                    }
                }
                if let chmodMode, !chmodMode.isEmpty,
                   chmodMode.range(of: #"^[0-7]{3,4}$"#, options: .regularExpression) != nil {
                    lines.append("chmod -R \(chmodMode) \(Self.shSingleQuote(resolvedDst)) 2>/dev/null || true")
                }

            case .addURL(let url, let destination):
                if isOffline {
                    lines.append("echo '[boo_box/dockerfile] skipping remote ADD \(Self.shSingleQuote(url)) (Offline mode)'")
                    continue
                }
                let resolvedDst = Self.resolveGuestDest(destination, workdir: currentWorkdir)
                let targetFile: String
                if destination.hasSuffix("/") || destination == "." {
                    let fname = URL(string: url)?.lastPathComponent ?? "download"
                    lines.append("mkdir -p \(Self.shSingleQuote(resolvedDst))")
                    targetFile = (resolvedDst as NSString).appendingPathComponent(fname)
                } else {
                    let parent = (resolvedDst as NSString).deletingLastPathComponent
                    if !parent.isEmpty && parent != "/" {
                        lines.append("mkdir -p \(Self.shSingleQuote(parent))")
                    }
                    targetFile = resolvedDst
                }
                lines.append("curl -fsSL \(Self.shSingleQuote(url)) -o \(Self.shSingleQuote(targetFile)) || echo '[boo_box/dockerfile] warning: ADD download failed'")

            case .run(let cmd, _, _):
                lines.append("echo '[boo_box/dockerfile] RUN ...'")
                let b64 = Data((cmd + "\n").utf8).base64EncodedString()
                lines.append("echo '\(b64)' | base64 -d > /tmp/.boobox-run.sh && sh /tmp/.boobox-run.sh || echo '[boo_box/dockerfile] warning: RUN step exited non-zero'")
                lines.append("rm -f /tmp/.boobox-run.sh")

            case .note(let msg):
                lines.append("echo '[boo_box/dockerfile] note: \(Self.shSingleQuote(msg))'")
            }
        }

        // 4. Hook final WORKDIR + optional CMD/EXPOSE hint into interactive /root/.zshrc
        if let wd = finalWorkdir, !wd.isEmpty {
            let wdQ = Self.shSingleQuote(wd)
            lines.append("mkdir -p \(wdQ)")
            lines.append("grep -q 'boobox-dockerfile-workdir' /root/.zshrc 2>/dev/null || printf '\\n# boobox-dockerfile-workdir\\n[ \"$PWD\" = \"/root\" ] && [ -d \(wdQ) ] && cd \(wdQ)\\n' >> /root/.zshrc")
        }
        if let cmd = defaultCommand, !cmd.isEmpty {
            let cmdB64 = Data((cmd + "\n").utf8).base64EncodedString()
            lines.append("echo '\(cmdB64)' | base64 -d > /root/.boobox-dockerfile-cmd")
        }

        lines.append("echo '[boo_box/dockerfile] setup finished'")
        return lines.joined(separator: "\n")
    }

    private static func resolveGuestDest(_ dst: String, workdir: String) -> String {
        if dst.hasPrefix("/") { return dst }
        if dst == "." || dst == "./" { return workdir }
        let clean = dst.hasPrefix("./") ? String(dst.dropFirst(2)) : dst
        if workdir == "/" { return "/" + clean }
        return workdir + "/" + clean
    }

    private static func normalizeRelativeSource(_ raw: String) -> String {
        var s = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        while s.hasPrefix("./") { s = String(s.dropFirst(2)) }
        if s.hasPrefix("/") { s = String(s.dropFirst()) }
        return s
    }

    static func isSafeRelativeSource(_ src: String) -> Bool {
        if src.isEmpty || src == "." { return true }
        let components = src.split(separator: "/")
        return !components.contains("..")
    }

    private static func shSingleQuote(_ s: String) -> String {
        "'" + s.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }

    private static func shDoubleEscape(_ s: String) -> String {
        s.replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "\"", with: "\\\"")
            .replacingOccurrences(of: "$", with: "\\$")
            .replacingOccurrences(of: "`", with: "\\`")
    }

    private static func shDoubleEscapePreservingVars(_ s: String) -> String {
        s.replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "\"", with: "\\\"")
            .replacingOccurrences(of: "`", with: "\\`")
    }
}

enum DockerfileParser {
    /// Standard Dockerfile / Containerfile locations checked during automatic discovery.
    static let standardCandidateRelativePaths: [String] = [
        "Dockerfile",
        "dockerfile",
        "Containerfile",
        "Dockerfile.dev",
        ".devcontainer/Dockerfile",
        "docker/Dockerfile",
    ]

    /// Detects the first Dockerfile/Containerfile inside a directory (non-recursive except standard subpaths).
    static func detectDockerfile(in directoryURL: URL) -> URL? {
        let fm = FileManager.default
        let base = directoryURL.resolvingSymlinksInPath()
        for rel in standardCandidateRelativePaths {
            let candidate = base.appendingPathComponent(rel)
            var isDir: ObjCBool = false
            if fm.fileExists(atPath: candidate.path, isDirectory: &isDir), !isDir.boolValue {
                return candidate
            }
        }
        return nil
    }

    /// Resolves the active Dockerfile URL and context directory for a PrivateVMConfig.
    /// Returns `(dockerfileURL, contextDirURL, wasAutoDetected)` or `nil` if none configured/detected.
    static func resolveDockerfile(for vmConfig: PrivateVMConfig) -> (url: URL, contextDir: URL, autoDetected: Bool)? {
        let fm = FileManager.default
        let explicit = vmConfig.dockerfilePath.trimmingCharacters(in: .whitespacesAndNewlines)
        if !explicit.isEmpty {
            let expanded = (explicit as NSString).expandingTildeInPath
            var isDir: ObjCBool = false
            guard fm.fileExists(atPath: expanded, isDirectory: &isDir) else { return nil }
            let url = URL(fileURLWithPath: expanded).resolvingSymlinksInPath()
            if isDir.boolValue {
                // If user pointed to a folder containing a Dockerfile, auto-resolve inside it
                if let detected = detectDockerfile(in: url) {
                    return (detected, url, true)
                }
                return nil
            }
            // Context dir: if inside `.devcontainer/` or `docker/`, use parent project dir; otherwise Dockerfile's folder
            let parentDir = url.deletingLastPathComponent()
            let parentName = parentDir.lastPathComponent.lowercased()
            let contextDir = (parentName == ".devcontainer" || parentName == "docker")
                ? parentDir.deletingLastPathComponent()
                : parentDir
            return (url, contextDir, false)
        }

        if vmConfig.autoDetectDockerfile, let sharedURL = vmConfig.resolvedSharedHostURL,
           let detected = detectDockerfile(in: sharedURL) {
            return (detected, sharedURL, true)
        }
        return nil
    }

    /// Parses a Dockerfile from disk into a structured `ParsedDockerfile`.
    static func parse(at fileURL: URL, contextDirectoryURL: URL? = nil) throws -> ParsedDockerfile {
        let text = try String(contentsOf: fileURL, encoding: .utf8)
        let ctxDir = contextDirectoryURL ?? {
            let p = fileURL.deletingLastPathComponent()
            let name = p.lastPathComponent.lowercased()
            return (name == ".devcontainer" || name == "docker") ? p.deletingLastPathComponent() : p
        }()
        return parse(content: text, sourceURL: fileURL, contextDirectoryURL: ctxDir)
    }

    /// Parses raw Dockerfile content into a `ParsedDockerfile` (pure function; easy to unit-test).
    static func parse(
        content: String,
        sourceURL: URL,
        contextDirectoryURL: URL
    ) -> ParsedDockerfile {
        let logicalInstructions = extractLogicalInstructions(from: content)

        struct StageBuilder {
            var baseImage: String = ""
            var stageName: String? = nil
            var args: [String: String] = [:]
            var envVars: [(key: String, value: String)] = []
            var workdir: String = "/root"
            var hasExplicitWorkdir: Bool = false
            var exposedPorts: [String] = []
            var defaultCommand: String? = nil
            var steps: [ParsedDockerfile.Step] = []
            var warnings: [String] = []
            var requiresCopyContext: Bool = false
        }

        var globalArgs: [String: String] = [:]
        var stages: [StageBuilder] = []

        func activeStageIndex() -> Int {
            if stages.isEmpty {
                stages.append(StageBuilder(args: globalArgs))
            }
            return stages.count - 1
        }

        for inst in logicalInstructions {
            let op = inst.keyword.uppercased()
            let rawArg = inst.rest

            switch op {
            case "FROM":
                let tokens = splitRespectingQuotes(rawArg).filter { !$0.hasPrefix("--") }
                let rawImage = tokens.first ?? ""
                let expandedImage = expandArgs(rawImage, args: globalArgs)
                var stageAlias: String? = nil
                if let asIdx = tokens.firstIndex(where: { $0.uppercased() == "AS" }), asIdx + 1 < tokens.count {
                    stageAlias = tokens[asIdx + 1]
                }
                var stage = StageBuilder(baseImage: expandedImage, stageName: stageAlias, args: globalArgs)
                stage.args = globalArgs
                stages.append(stage)

            case "ARG":
                let cleaned = rawArg.trimmingCharacters(in: .whitespacesAndNewlines)
                guard !cleaned.isEmpty else { continue }
                let (key, val): (String, String?)
                if let eq = cleaned.firstIndex(of: "=") {
                    key = String(cleaned[..<eq]).trimmingCharacters(in: .whitespacesAndNewlines)
                    let rawVal = String(cleaned[cleaned.index(after: eq)...]).trimmingCharacters(in: .whitespacesAndNewlines)
                    val = unquote(rawVal)
                } else {
                    key = cleaned
                    val = nil
                }
                guard !key.isEmpty else { continue }
                if stages.isEmpty {
                    if let val { globalArgs[key] = val }
                } else {
                    let idx = activeStageIndex()
                    if let val {
                        stages[idx].args[key] = expandArgs(val, args: stages[idx].args)
                    } else if let g = globalArgs[key] {
                        stages[idx].args[key] = g
                    }
                }

            case "ENV":
                let idx = activeStageIndex()
                let pairs = parseEnvPairs(rawArg)
                for (k, rawVal) in pairs {
                    guard isValidEnvKey(k) else { continue }
                    let expanded = expandArgs(rawVal, args: stages[idx].args)
                    if let existing = stages[idx].envVars.firstIndex(where: { $0.key == k }) {
                        stages[idx].envVars[existing] = (key: k, value: expanded)
                    } else {
                        stages[idx].envVars.append((key: k, value: expanded))
                    }
                    stages[idx].steps.append(.env(key: k, value: expanded))
                }

            case "WORKDIR":
                let idx = activeStageIndex()
                let expanded = unquote(expandArgs(rawArg.trimmingCharacters(in: .whitespacesAndNewlines), args: stages[idx].args))
                guard !expanded.isEmpty else { continue }
                let resolved: String
                if expanded.hasPrefix("/") {
                    resolved = expanded
                } else {
                    let base = stages[idx].hasExplicitWorkdir ? stages[idx].workdir : ""
                    resolved = (base.isEmpty ? "/" : base + "/") + expanded
                }
                let normalized = URL(fileURLWithPath: resolved).standardizedFileURL.path
                stages[idx].workdir = normalized
                stages[idx].hasExplicitWorkdir = true
                stages[idx].steps.append(.workdir(normalized))

            case "COPY", "ADD":
                let idx = activeStageIndex()
                // Support heredoc COPY <<EOF /dest
                if let heredoc = inst.heredoc {
                    let tokens = splitRespectingQuotes(rawArg).filter { !$0.hasPrefix("--") && !$0.hasPrefix("<<") }
                    if let dst = tokens.last {
                        let expandedDst = expandArgs(dst, args: stages[idx].args)
                        let b64 = Data(heredoc.body.utf8).base64EncodedString()
                        let cmd = "mkdir -p \"$(dirname \(shQuoteSimple(expandedDst)))\" && echo '\(b64)' | base64 -d > \(shQuoteSimple(expandedDst))"
                        stages[idx].steps.append(.run(command: cmd, originalCommand: nil, translatedFromApt: false))
                    }
                    continue
                }

                let tokens = splitRespectingQuotes(rawArg)
                var fromStage: String? = nil
                var chmodMode: String? = nil
                var positional: [String] = []
                for tok in tokens {
                    if tok.hasPrefix("--from=") {
                        fromStage = String(tok.dropFirst("--from=".count))
                    } else if tok.hasPrefix("--chmod=") {
                        chmodMode = String(tok.dropFirst("--chmod=".count))
                    } else if tok.hasPrefix("--") {
                        continue // ignore --chown / --link
                    } else {
                        positional.append(tok)
                    }
                }
                if let fromStage {
                    stages[idx].warnings.append("Multi-stage `COPY --from=\(fromStage)` skipped (Private VM runs the final stage directly on Alpine Linux).")
                    continue
                }
                // JSON exec-array form: COPY ["src", "dst"]
                if positional.count == 1, let arr = parseJSONStringArray(rawArg), arr.count >= 2 {
                    positional = arr
                }
                guard positional.count >= 2 else { continue }
                let dst = expandArgs(positional.removeLast(), args: stages[idx].args)
                let srcs = positional.map { expandArgs($0, args: stages[idx].args) }

                if op == "ADD", srcs.count == 1,
                   (srcs[0].hasPrefix("http://") || srcs[0].hasPrefix("https://")) {
                    stages[idx].steps.append(.addURL(url: srcs[0], destination: dst))
                } else {
                    stages[idx].requiresCopyContext = true
                    stages[idx].steps.append(.copy(sources: srcs, destination: dst, chmod: chmodMode))
                }

            case "RUN":
                let idx = activeStageIndex()
                var cmdBody: String
                if let heredoc = inst.heredoc {
                    cmdBody = heredoc.body
                } else {
                    let stripped = stripLeadingBuildkitFlags(rawArg)
                    if let arr = parseJSONStringArray(stripped) {
                        cmdBody = arr.map { shQuoteIfNeeded($0) }.joined(separator: " ")
                    } else {
                        cmdBody = stripped
                    }
                }
                cmdBody = expandArgs(cmdBody.trimmingCharacters(in: .whitespacesAndNewlines), args: stages[idx].args)
                guard !cmdBody.isEmpty else { continue }

                if let translated = translateAptCommandIfNeeded(cmdBody) {
                    stages[idx].steps.append(.run(
                        command: translated.command,
                        originalCommand: cmdBody,
                        translatedFromApt: true
                    ))
                    stages[idx].warnings.append(translated.warning)
                } else {
                    stages[idx].steps.append(.run(command: cmdBody, originalCommand: nil, translatedFromApt: false))
                }

            case "EXPOSE":
                let idx = activeStageIndex()
                let ports = rawArg
                    .split(whereSeparator: { $0.isWhitespace })
                    .map { expandArgs(String($0), args: stages[idx].args) }
                    .filter { !$0.isEmpty }
                for p in ports where !stages[idx].exposedPorts.contains(p) {
                    stages[idx].exposedPorts.append(p)
                }

            case "CMD", "ENTRYPOINT":
                let idx = activeStageIndex()
                let cleaned = rawArg.trimmingCharacters(in: .whitespacesAndNewlines)
                guard !cleaned.isEmpty else { continue }
                if let arr = parseJSONStringArray(cleaned) {
                    stages[idx].defaultCommand = arr.joined(separator: " ")
                } else {
                    stages[idx].defaultCommand = cleaned
                }

            default:
                break // LABEL, USER, VOLUME, SHELL, STOPSIGNAL, HEALTHCHECK ignored safely
            }
        }

        let finalStage = stages.last ?? StageBuilder()
        var warnings = finalStage.warnings
        let (runtimePkgs, installsBun, baseWarning) = inferAlpineRuntime(for: finalStage.baseImage)
        if let baseWarning {
            warnings.insert(baseWarning, at: 0)
        }
        if stages.count > 1 {
            warnings.append("Multi-stage Dockerfile (\(stages.count) stages): applying final stage\(finalStage.stageName.map { " '\($0)'" } ?? "").")
        }

        return ParsedDockerfile(
            sourceURL: sourceURL,
            contextDirectoryURL: contextDirectoryURL,
            baseImage: finalStage.baseImage,
            stageName: finalStage.stageName,
            stageCount: max(1, stages.count),
            baseRuntimePackages: runtimePkgs,
            installsBun: installsBun,
            envVars: finalStage.envVars,
            finalWorkdir: finalStage.hasExplicitWorkdir ? finalStage.workdir : nil,
            exposedPorts: finalStage.exposedPorts,
            defaultCommand: finalStage.defaultCommand,
            steps: finalStage.steps,
            warnings: deduplicatePreservingOrder(warnings),
            requiresCopyContext: finalStage.requiresCopyContext
        )
    }

    // MARK: - Logical Line / Heredoc Extraction

    private struct HeredocBlock {
        let delimiter: String
        let stripLeadingTabs: Bool
        let body: String
    }

    private struct LogicalInstruction {
        let keyword: String
        let rest: String
        let heredoc: HeredocBlock?
    }

    private static func extractLogicalInstructions(from content: String) -> [LogicalInstruction] {
        let rawLines = content
            .replacingOccurrences(of: "\r\n", with: "\n")
            .replacingOccurrences(of: "\r", with: "\n")
            .components(separatedBy: "\n")

        var escapeChar: Character = "\\"
        var index = 0

        // Parse leading parser directives (e.g. `# escape=\``)
        while index < rawLines.count {
            let trimmed = rawLines[index].trimmingCharacters(in: .whitespaces)
            if trimmed.hasPrefix("#") {
                let body = trimmed.dropFirst().trimmingCharacters(in: .whitespaces)
                if body.lowercased().hasPrefix("escape="), let ch = body.dropFirst("escape=".count).first {
                    escapeChar = ch
                    index += 1
                    continue
                }
                if body.lowercased().hasPrefix("syntax=") {
                    index += 1
                    continue
                }
            }
            break
        }

        var results: [LogicalInstruction] = []
        while index < rawLines.count {
            let line = rawLines[index]
            let trimmed = line.trimmingCharacters(in: .whitespaces)
            if trimmed.isEmpty || trimmed.hasPrefix("#") {
                index += 1
                continue
            }

            // Accumulate line continuations
            var combined = line
            while combined.trimmingCharacters(in: .whitespaces).last == escapeChar, index + 1 < rawLines.count {
                // Remove trailing escape char + optional trailing whitespace
                if let escIdx = combined.lastIndex(of: escapeChar) {
                    combined = String(combined[..<escIdx])
                }
                index += 1
                let nextLine = rawLines[index]
                let nextTrim = nextLine.trimmingCharacters(in: .whitespaces)
                if nextTrim.hasPrefix("#") {
                    // Comment inside continuation is skipped in Dockerfiles; keep continuation open
                    combined.append(escapeChar)
                    continue
                }
                combined.append(" ")
                combined.append(nextLine)
            }
            index += 1

            let cleanCombined = combined.trimmingCharacters(in: .whitespaces)
            guard let spaceIdx = cleanCombined.firstIndex(where: { $0.isWhitespace }) else { continue }
            let keyword = String(cleanCombined[..<spaceIdx])
            let rest = String(cleanCombined[spaceIdx...]).trimmingCharacters(in: .whitespaces)

            // Check for BuildKit heredoc on RUN or COPY (`<<EOF`, `<<-EOF`, `<<'EOF'`)
            var heredocBlock: HeredocBlock? = nil
            if (keyword.uppercased() == "RUN" || keyword.uppercased() == "COPY"),
               let hdSpec = parseHeredocMarker(in: rest) {
                var bodyLines: [String] = []
                while index < rawLines.count {
                    let hLine = rawLines[index]
                    index += 1
                    let compareLine = hdSpec.stripTabs ? hLine.drop(while: { $0 == "\t" }) : Substring(hLine)
                    if compareLine == hdSpec.delimiter {
                        break
                    }
                    bodyLines.append(String(compareLine))
                }
                heredocBlock = HeredocBlock(
                    delimiter: hdSpec.delimiter,
                    stripLeadingTabs: hdSpec.stripTabs,
                    body: bodyLines.joined(separator: "\n")
                )
            }

            results.append(LogicalInstruction(keyword: keyword, rest: rest, heredoc: heredocBlock))
        }

        return results
    }

    private static func parseHeredocMarker(in rest: String) -> (delimiter: String, stripTabs: Bool)? {
        guard let range = rest.range(of: #"<<(-)?['"]?([A-Za-z_][A-Za-z0-9_]*)['"]?"#, options: .regularExpression) else {
            return nil
        }
        var token = String(rest[range])
        token.removeFirst(2) // remove "<<"
        var stripTabs = false
        if token.hasPrefix("-") {
            stripTabs = true
            token.removeFirst()
        }
        token = token.trimmingCharacters(in: CharacterSet(charactersIn: "'\""))
        guard !token.isEmpty else { return nil }
        return (token, stripTabs)
    }

