    private static func inferAlpineRuntime(for baseImage: String) -> (packages: [String], installsBun: Bool, warning: String?) {
        let lower = baseImage.lowercased().trimmingCharacters(in: .whitespacesAndNewlines)
        guard !lower.isEmpty else { return ([], false, nil) }

        // Strip registry prefix (`docker.io/library/node:22` -> `node:22`)
        let repo = lower.split(separator: "/").last.map(String.init) ?? lower
        let name = repo.split(separator: ":").first.map(String.init) ?? repo

        if name == "node" || name.hasPrefix("node-") {
            return (["nodejs", "npm"], false, nil)
        }
        if name == "bun" || lower.contains("oven/bun") {
            return (["curl", "unzip", "libstdc++", "libgcc"], true, nil)
        }
        if name == "python" || name.hasPrefix("python-") {
            return (["python3", "py3-pip"], false, nil)
        }
        if name == "golang" || name == "go" {
            return (["go"], false, nil)
        }
        if name == "rust" {
            return (["cargo", "rust"], false, nil)
        }
        if name == "ruby" {
            return (["ruby", "ruby-bundler"], false, nil)
        }
        if name == "alpine" || lower.contains("alpine") {
            return ([], false, nil)
        }
        if name == "ubuntu" || name == "debian" || lower.contains("bookworm") || lower.contains("bullseye") || lower.contains("jammy") || lower.contains("noble") {
            return ([], false, "Base image '\(baseImage)' is Debian/Ubuntu-based; Private VM runs Alpine 3.21 arm64 (common apt-get packages are translated to apk automatically).")
        }
        return ([], false, "Base image '\(baseImage)' runs on boo_box's Alpine 3.21 arm64 microVM; install any custom packages via RUN.")
    }

